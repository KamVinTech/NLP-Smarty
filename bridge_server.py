"""
Persistent JSON-RPC / JSON-Lines Sidecar Bridge for VS Code Extension
=====================================================================
Commands supported over stdin/stdout JSON-Lines:
  1. `"command": "optimize"`       -> Runs deterministic 4-stage pipeline (`pipeline.py`)
  2. `"command": "compare_hf"`     -> Runs pipeline + forwards both Raw & Compiled prompts to HuggingFace (`app.py` or built-in HF client)
  3. `"command": "audit_pair"`     -> Deterministically audits Raw vs. Optimized responses generated by VS Code's `vscode.lm`
  4. `"command": "clear_cache"`    -> Clears `PROMPT_CACHE`
"""

from __future__ import annotations

